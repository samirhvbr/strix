"""Regenerate ``items.yaml`` from section 5 of the consolidated product document.

The product document (``PENTEST-11-DOCUMENTACAO-PRODUTO-CONSOLIDADA.md``) lives outside this
repository and stays the authority for the full 171-check catalog. This script copies its section 5
verbatim, so nothing is retyped by hand. Item weights and applicability are curated separately in
``selection.yaml``.

    uv run python scripts/generate_assessment_catalog.py <path-to-PENTEST-11.md>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml


TARGET = (
    Path(__file__).resolve().parent.parent / "strix" / "core" / "assessment_catalog" / "items.yaml"
)
HEADER = (
    "# GENERATED by scripts/generate_assessment_catalog.py from section 5 of\n"
    "# PENTEST-11-DOCUMENTACAO-PRODUTO-CONSOLIDADA.md. Do not edit by hand.\n"
    "# The source text is kept verbatim (Portuguese) because that document is the authority for\n"
    "# the catalog; English labels for the curated items live in selection.yaml.\n"
)
FAMILY = re.compile(r"^### (5\.\d+)\. (.+)$")
ITEM = re.compile(r"^- \[ \] \*\*(5\.\d+\.\d+)\.\*\* (.+)$")


def parse(text: str) -> list[dict[str, object]]:
    start = text.index("## 5. Cat")
    end = text.index("\n## 6.", start)
    families: list[dict[str, object]] = []
    note: list[str] = []
    for line in text[start:end].splitlines():
        if match := FAMILY.match(line):
            families.append({"id": match[1], "title": match[2], "items": []})
            note = []
        elif match := ITEM.match(line):
            if not families or not match[1].startswith(str(families[-1]["id"]) + "."):
                raise ValueError(f"Item {match[1]} sits outside its family")
            items = families[-1]["items"]
            assert isinstance(items, list)
            items.append({"id": match[1], "text": match[2]})
        elif line.strip() and families and families[-1]["items"]:
            note.append(line.strip())
            families[-1]["conditions"] = " ".join(note)
        elif line.startswith("- ["):
            raise ValueError(f"Unrecognised checklist line: {line}")
    return families


def main() -> None:
    families = parse(Path(sys.argv[1]).read_text(encoding="utf-8"))
    total = sum(len(f["items"]) for f in families)  # type: ignore[arg-type]
    TARGET.write_text(
        HEADER
        + yaml.safe_dump(
            {"catalog_version": 1, "families": families},
            allow_unicode=True,
            sort_keys=False,
            width=100,
        ),
        encoding="utf-8",
    )
    print(f"{len(families)} families, {total} items -> {TARGET}")  # noqa: T201


if __name__ == "__main__":
    main()
